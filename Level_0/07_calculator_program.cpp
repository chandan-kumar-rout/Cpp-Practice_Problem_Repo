// Q.7.write a calculator program performing addition, subtraction,multiplication and division. 
#include <iostream>
using namespace std; 
int main() 
{
     int a = 10; 
     int b = 5; 

     cout << "Addition: " << a + b << endl; 
     cout << "Subtraction: " << a - b << endl; 
     cout << "Multiplication: " << a * b << endl; 
     cout << "Division: " << a / b << endl; 

     return 0;
}