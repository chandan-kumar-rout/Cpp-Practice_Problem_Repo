// Q.15. print escape sequences in c++.
#include <iostream> 
using namespace std; 
int main() 
{
    cout << "Escape Sequences in C++: " << endl; 
    cout << "New Line: \\n" << endl; 
    cout << "Tab: \\t" << endl; 
    cout << "Backslash: \\\\" << endl; 
    cout << "Double Quote: \\\"" << endl; 
    cout << "Single Quote: \\\'" << endl; 

    return 0; 
}