//Q.17. write a program using escape characters in c++. 
#include <iostream> 
using namespace std; 
int main() 
{
    cout << "Hello, World!\n"; // newline escape character 
    cout << "This is a tab:\tHere.\n"; // tab escape character 
    cout << "This is a backslash:\\\n"; // backslash escape character 
    cout << "This is a quote: \"Hello, World!\"\n"; // double quote escape character 

    return 0; 
}