//Q.19. write a program to demonstrate the use of punctuators in C++.
#include <iostream>
using namespace std;

int main()
{
    int a = 10;
    int b = 20;
    int c = a + b; // + is a punctuator

    cout << "The sum is: " << c << endl;

    return 0;
}

/*
A punctuator is a special character in programming that organizes and structures code syntax. It tells the compiler how statements, blocks, and expressions are grouped or terminated.
Key Examples
; (Semicolon) – Ends a statement.
{ } (Curly braces) – Defines a code block.
( ) (Parentheses) – Used for functions and conditions.
, (Comma) – Separates items in a list.
*/