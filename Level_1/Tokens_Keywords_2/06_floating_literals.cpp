// Q. 6. write a program using floating literals in c++.
#include <iostream> 
using namespace std; 
int main() 
{
     float pi = 3.14; 
     double num = 10.5678; 

     cout << pi << endl; 
     cout << num << endl; 

     return 0; 

}

/*
Explanation

Floating literals contain decimal point.

Examples:

3.14
0.5
10.75

*/