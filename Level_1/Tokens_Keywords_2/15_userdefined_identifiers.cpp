// Q.15. write a program using user-defined identifiers in c++. 
#include <iostream> 
using namespace std; 
int main() 
{
    int salary = 50000; // 'salary' is a user-defined identifier 
    int bonus = 5000; // 'bonus' is a user-defined identifier 
    int totalIncome = salary + bonus; // 'totalIncome' is a user-defined identifier 

    cout << "Total Income: " << totalIncome << endl; 

    return 0; 
}

/*identifiers created by programmers are called user-defined identifiers. 
*/