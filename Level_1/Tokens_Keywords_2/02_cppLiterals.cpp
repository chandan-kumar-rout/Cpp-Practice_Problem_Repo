//Q.2. write a program using some different literals in c++.
#include <iostream>

using namespace std;

int main()
{
    int a = 10;
    float b = 5.5;
    char c = 'A';
    bool d = true;
    string e = "C++";

    cout << a << endl;
    cout << b << endl;
    cout << c << endl;
    cout << d << endl;
    cout << e;

    return 0;
}