// Q.2. Write a C++ program containing multiple statements inside main().
#include <iostream>

using namespace std;

int main()
{
    int a = 10;
    int b = 20;

    cout << "Value of a = " << a << endl;
    cout << "Value of b = " << b << endl;

    int sum = a + b;

    cout << "Sum = " << sum;

    return 0;
}